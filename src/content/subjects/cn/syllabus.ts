export type ModuleSpec = (typeof modules)[number];
export type ModuleId = ModuleSpec["id"];

const bulletsByModule = new Map<string, ReadonlySet<string>>(
  modules.map((module) => [module.id, new Set<string>(module.bullets)]),
);

export function syllabusBullet(moduleId: ModuleId, bullet: string): string {
  const known = bulletsByModule.get(moduleId);
  if (!known?.has(bullet)) {
    throw new Error(`Unknown ${moduleId} syllabus bullet: ${bullet}`);
  }
  return bullet;
}
